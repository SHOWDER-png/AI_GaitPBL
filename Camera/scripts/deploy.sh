#!/usr/bin/env bash
# Copy the cross-built camera app, the pose model and ONNX Runtime to the FRDM-IMX95 (SCRUM-176).
#
#   Camera/scripts/deploy.sh root@<board-ip> [--build build-imx95] [--dest /root/gait] [--dry-run]
#
# Board layout after deploy (DEST, default /root/gait):
#   posture_detection, camera_capture (if built)
#   lib/libonnxruntime.so.1          found through the binaries' RPATH ($ORIGIN/lib)
#   models/yolov8n-pose.onnx         main.cpp loads models/... relative to the working dir
#   run_posture.sh                   sets LIBCAMERA_PIPELINES_MATCH_LIST=nxp/neo and starts the app
#
# Refuses to copy a binary that is not aarch64, or when a file is missing. --dry-run prints the
# ssh/scp commands without touching the board. Set SSH_OPTS for extra ssh/scp options
# (for example SSH_OPTS="-o StrictHostKeyChecking=accept-new").
set -euo pipefail

CAMERA_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BUILD="$CAMERA_DIR/build-imx95"
DEST="/root/gait"
DRY_RUN=0
TARGET=""
ORT_VERSION="1.19.0"

usage() { sed -n '2,14p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 2; }

while [ $# -gt 0 ]; do
    case "$1" in
        --build) BUILD="$2"; shift 2 ;;
        --dest) DEST="$2"; shift 2 ;;
        --dry-run) DRY_RUN=1; shift ;;
        -h|--help) usage ;;
        -*) echo "ERROR: unknown option $1" >&2; usage ;;
        *) [ -z "$TARGET" ] || { echo "ERROR: one board only" >&2; usage; }; TARGET="$1"; shift ;;
    esac
done
[ -n "$TARGET" ] || { echo "ERROR: board address missing (e.g. root@192.168.1.50)" >&2; usage; }
case "$DEST" in
    /*) ;;
    *) echo "ERROR: --dest must be an absolute path on the board" >&2; exit 2 ;;
esac
case "$DEST" in
    *[!A-Za-z0-9_./-]*) echo "ERROR: --dest may only contain letters, digits, _ . / -" >&2; exit 2 ;;
esac

ORT_LIB="$CAMERA_DIR/third_party/onnxruntime-linux-aarch64-$ORT_VERSION/lib/libonnxruntime.so.$ORT_VERSION"
MODEL="$CAMERA_DIR/models/yolov8n-pose.onnx"
APP="$BUILD/posture_detection"
CAPTURE="$BUILD/camera_capture"

fail=0
need() { [ -f "$1" ] || { echo "ERROR: missing $2: $1" >&2; fail=1; }; }
need "$APP" "cross-built app (cmake --build $BUILD)"
need "$MODEL" "pose model"
need "$ORT_LIB" "ONNX Runtime aarch64 (run scripts/fetch_onnxruntime.sh)"
[ "$fail" -eq 0 ] || exit 1

is_aarch64() {
    # ELF header: class 64-bit (byte 4 = 2), machine EM_AARCH64 = 183 = 0xb7 (bytes 18-19, LE)
    local header
    header="$(od -An -tx1 -N20 "$1" | tr -d ' \n')"
    [ "${header:0:8}" = "7f454c46" ] && [ "${header:8:2}" = "02" ] && [ "${header:36:4}" = "b700" ]
}
for bin in "$APP" "$ORT_LIB"; do
    is_aarch64 "$bin" || { echo "ERROR: $bin is not an aarch64 ELF file; build with cmake/aarch64.cmake" >&2; exit 1; }
done
FILES_BIN=("$APP")
if [ -f "$CAPTURE" ]; then
    is_aarch64 "$CAPTURE" || { echo "ERROR: $CAPTURE is not aarch64" >&2; exit 1; }
    FILES_BIN+=("$CAPTURE")
fi

RUN_SCRIPT="$(mktemp)"
trap 'rm -f "$RUN_SCRIPT"' EXIT
cat > "$RUN_SCRIPT" <<EOF
#!/bin/sh
# Generated by Camera/scripts/deploy.sh. Starts the camera app on the FRDM-IMX95.
cd "$DEST" || exit 1
export LIBCAMERA_PIPELINES_MATCH_LIST=nxp/neo    # NeoISP pipeline, see board/FRDM_IMX95_BOARD_SETUP.md
exec ./posture_detection "\$@"
EOF

run() {
    if [ "$DRY_RUN" -eq 1 ]; then printf 'DRY-RUN:'; printf ' %q' "$@"; printf '\n'
    else "$@"; fi
}
read -r -a EXTRA_OPTS <<< "${SSH_OPTS:-}"   # split on spaces, no globbing
SSH=(ssh "${EXTRA_OPTS[@]}")
SCP=(scp "${EXTRA_OPTS[@]}")

echo "Deploying to $TARGET:$DEST"
run "${SSH[@]}" "$TARGET" "mkdir -p '$DEST/lib' '$DEST/models'"
run "${SCP[@]}" "${FILES_BIN[@]}" "$TARGET:$DEST/"
run "${SCP[@]}" "$ORT_LIB" "$TARGET:$DEST/lib/libonnxruntime.so.1"
run "${SCP[@]}" "$MODEL" "$TARGET:$DEST/models/yolov8n-pose.onnx"
run "${SCP[@]}" "$RUN_SCRIPT" "$TARGET:$DEST/run_posture.sh"
run "${SSH[@]}" "$TARGET" "chmod +x '$DEST/run_posture.sh' '$DEST/posture_detection' && cd '$DEST' && ./posture_detection --help >/dev/null && echo 'Board check: posture_detection starts and finds libonnxruntime'"
echo "Done. On the board: $DEST/run_posture.sh"
